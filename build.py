def write(rel, content):
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)


def main():
    write("index.html", home())
    write("aura/index.html", aura_page())
    write("projects/index.html", projects_page())
    for pr in PROJECTS:
        write(f"projects/{pr['slug']}/index.html", project_page(pr))
    write("about/index.html", about_page())
    write("contact/index.html", contact_page())
    write("404.html", not_found())
    urls = ["", "aura/", "projects/"] + [f"projects/{pr['slug']}/" for pr in PROJECTS] + ["about/", "contact/"]
